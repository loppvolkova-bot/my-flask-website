def clean_text(text):
    """ Очистка текста от лишних символов для стабильной векторизации """
    text = re.sub(r'[^а-яа-ёa-z\s]', '', text.lower())
    return text.strip()

# Подготовка NLP-корпуса
corpus = []
reply_mapping = []

for item in AI_KNOWLEDGE:
    combined_patterns = " ".join(item["patterns"])
    corpus.append(clean_text(combined_patterns))
    reply_mapping.append(item["reply"])

# Обучаем векторизатор при старте сервера
vectorizer = TfidfVectorizer()
X_corpus = vectorizer.fit_transform(corpus)


