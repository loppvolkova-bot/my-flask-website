@app.route('/ai-chat', methods=['POST'])
def ai_chat():
    data = request.get_json(silent=True) or {}
    user_message = data.get('message', '').lower().strip()
    
    if not user_message:
        return jsonify({"reply": "🤖 ИИ-Ассистент: Пожалуйста, введите ваш вопрос."})
    
    # 1. Математическая векторизация входящего вопроса пользователя
    X_user = vectorizer.transform([user_message])
    
    # 2. Расчет косинусного сходства между вопросом и всеми темами базы знаний
    similarity_scores = cosine_similarity(X_user, X_corpus)
    
    # Определяем индекс наиболее подходящего по смыслу ответа
    max_score_index = similarity_scores.argmax()
    max_score = similarity_scores[max_score_index]
    
    # Порог уверенности ИИ (если совпадение по смыслу более 12%)
    if max_score > 0.12:
        reply = reply_mapping[max_score_index]
    else:
        # Заглушка, если ИИ не понял абстрактный вопрос
        reply = "🤖 ИИ-Ассистент: Интересный вопрос! Моя нейросетевая модель пока только учится. Попробуйте спросить меня точнее, например: про 'Движкоины', 'квесты', 'мероприятия' или 'описание приложения'."
            
    return jsonify({"reply": reply})

