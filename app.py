# НАСТРОЙКА И ОБУЧЕНИЕ NLP-МОДЕЛИ ПРИ ЗАПУСКЕ СЕРВЕРА
corpus = []
reply_mapping = []

for item in AI_KNOWLEDGE:
    # Объединяем ключевые фразы каждой темы в единый текстовый вектор
    combined_patterns = " ".join(item["patterns"])
    corpus.append(combined_patterns)
    reply_mapping.append(item["reply"])

# Инициализируем векторизатор TF-IDF (переводит слова в математические веса)
vectorizer = TfidfVectorizer()
X_corpus = vectorizer.fit_transform(corpus)


